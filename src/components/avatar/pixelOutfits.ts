export type Bodice =
  | "tee"
  | "puff"
  | "long"
  | "tank"
  | "halter"
  | "tube"
  | "offshoulder"
  | "vest"
  | "bikini";

export type Lower =
  | "none"
  | "mini"
  | "skirt"
  | "tiers"
  | "tutu"
  | "gown"
  | "mermaid"
  | "shorts"
  | "pants"
  | "briefs"
  | "swimskirt";

export type Pattern =
  | "stripes"
  | "diagonal"
  | "dots"
  | "sparkle"
  | "plaid"
  | "ombre"
  | "zebra"
  | "rainbow"
  | "flowers"
  | "leaves"
  | "checks";

