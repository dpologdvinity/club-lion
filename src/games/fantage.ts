export type FantageGameId = (typeof FANTAGE_GAMES)[number]["id"];

export function isFantageGame(id: unknown): id is FantageGameId {
  return FANTAGE_GAMES.some((game) => game.id === id);
}

export function fantageGame(id: FantageGameId) {
  return FANTAGE_GAMES.find((game) => game.id === id) ?? FANTAGE_GAMES[0];
}
